#!/usr/bin/env python3
"""Generate sw.js with a content-hash version over the app-shell precache list."""
import hashlib, json, pathlib, sys

SHELL = [
    "./",
    "index.html",
    "styles.css",
    "qrcode.js",
    "assets/fonts.css",
    "manifest.webmanifest",
    "icon-192.png",
    "icon-512.png",
    "icon-maskable-192.png",
    "icon-maskable-512.png",
    "apple-touch-icon.png",
] + [f"js/{p.name}" for p in sorted(pathlib.Path("js").glob("*.js"))] \
  + [f"assets/fonts/{p.name}" for p in sorted(pathlib.Path("assets/fonts").glob("*.woff2"))]

def sha(path):
    p = path[2:] if path.startswith("./") else path
    if p == "":  # "./" shell root serves index.html
        p = "index.html"
    # Normalize CRLF so the version hash is stable across platforms
    # (Windows working trees are CRLF, Linux checkouts are LF).
    data = pathlib.Path(p).read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()

version = "qc-" + hashlib.sha256(
    "".join(sha(p) for p in SHELL).encode()
).hexdigest()[:12]

template = '''/* QuickChat service worker — generated by tools/build_sw.py, do not edit by hand.
   Version: __VERSION__
   Precache: __COUNT__ assets, ~__KB__ KB */
const VERSION = "__VERSION__";
const PRECACHE = __PRECACHE__;
const SHARE_CACHE = "qc-share";

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(VERSION)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k !== VERSION && k !== SHARE_CACHE).map((k) => caches.delete(k))
      ))
      .then(() => self.clients.claim())
  );
});

// Web Share Target (POST) — stash shared file, redirect into the app.
async function handleShare(request) {
  const params = new URLSearchParams();
  try {
    const fd = await request.formData();
    for (const key of ["title", "text", "url"]) {
      const v = fd.get(key);
      if (v) params.set(key, v);
    }
    const f = fd.get("file");
    if (f && typeof f !== "string" && f.size) {
      const cache = await caches.open(SHARE_CACHE);
      await cache.put("shared-file", new Response(f, {
        headers: {
          "Content-Type": f.type || "application/octet-stream",
          "X-Name": encodeURIComponent(f.name || "file"),
        },
      }));
      params.set("file", "1");
    }
  } catch (e) { /* fall through to redirect */ }
  return Response.redirect(new URL("./?" + params.toString(), self.registration.scope).href, 303);
}

function precached(request) {
  return caches.match(request, { ignoreSearch: true }).then((r) => r || Response.error());
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);

  if (request.method === "POST" && url.pathname.endsWith("/share-target")) {
    event.respondWith(handleShare(request));
    return;
  }
  if (request.method !== "GET") return;
  if (url.origin !== self.location.origin) return; // never touch cross-origin

  // App-shell assets: cache-first (guaranteed offline after first visit).
  if (PRECACHE.some((p) => url.pathname.endsWith(p.replace("./", "/")) || p === "./" && url.pathname.endsWith("/"))) {
    event.respondWith(precached(request));
    return;
  }

  // Navigations (incl. share-target GET and shortcuts): network, then cache, then offline shell.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((res) => {
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put("./", copy));
          return res;
        })
        .catch(() => caches.match(request, { ignoreSearch: true })
          .then((r) => r || caches.match("./")))
    );
    return;
  }

  // Other same-origin GETs (e.g. fetched fonts under scope): stale-while-revalidate.
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((cached) => {
      const fetched = fetch(request).then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put(request, copy));
        }
        return res;
      }).catch(() => cached);
      return cached || fetched;
    })
  );
});

// Allow the page to trigger an immediate takeover after an update.
self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
});
'''

total_kb = sum(pathlib.Path(p.lstrip("./")).stat().st_size for p in SHELL) // 1024
out = (template
       .replace("__VERSION__", version)
       .replace("__PRECACHE__", json.dumps(SHELL))
       .replace("__COUNT__", str(len(SHELL)))
       .replace("__KB__", str(total_kb)))
with open("sw.js", "w", encoding="utf-8", newline="\n") as f:
    f.write(out)
print(f"sw.js written: {version}, {len(SHELL)} assets, ~{total_kb} KB")
